/**
 * Generates client/src/lib/demoSnapshot.ts from a running dev backend so the
 * single-file export build can fall back to real content when no API is
 * reachable (e.g. the HTML is opened via file:// for offline demos).
 *
 * All entry images (seed placeholder art + external program photos) are
 * recoded to ~800px JPEG data URLs (via headless Chromium) so the demo
 * renders fully offline at a reasonable file size. Images that fail to
 * fetch keep their original URL; images that fail to recode keep the
 * original bytes (within the raw cap).
 *
 * Usage: node scripts/make-demo-snapshot.mjs   (dev server on :8787)
 */
import { writeFileSync } from 'node:fs';
import { chromium } from 'playwright';

const BASE = process.env.BASE ?? 'http://localhost:8787';
const RAW_CAP_BYTES = 3_000_000; // refuses to inline originals bigger than this
const TIMEOUT_MS = 15_000;
const MAX_WIDTH = 800;
const JPEG_QUALITY = 0.78;

const res = await fetch(`${BASE}/api/published`);
if (!res.ok) {
  console.error(`FAILED: ${BASE}/api/published -> ${res.status}`);
  process.exit(1);
}
const sections = await res.json();

// collect every image URL (seed art paths resolve against the dev server)
const urls = new Set();
for (const s of sections) {
  for (const e of s.entries) {
    if (!e.imageUrl) continue;
    const m = /^\/api\/seedimg\/[a-z-]+\/([a-z-]+\.svg)$/.exec(e.imageUrl);
    urls.add(m ? BASE + `/seed/${m[1]}` : e.imageUrl);
  }
}

/** Fetch raw image bytes; null when unavailable/too big. */
async function fetchImage(url) {
  try {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
    const imgRes = await fetch(url, { signal: ctrl.signal, redirect: 'follow' });
    clearTimeout(timer);
    const mime = (imgRes.headers.get('content-type') ?? '').split(';')[0];
    if (!imgRes.ok || !mime.startsWith('image/')) return null;
    const buf = Buffer.from(await imgRes.arrayBuffer());
    if (buf.length === 0 || buf.length > RAW_CAP_BYTES) return null;
    return { buf, mime };
  } catch {
    return null;
  }
}

// recode via headless Chromium: normalize to MAX_WIDTH-wide JPEG data URLs
const browser = await chromium.launch();
const page = await browser.newPage();
async function recodeToJpeg(buf, mime) {
  const src = `data:${mime};base64,${buf.toString('base64')}`;
  return page.evaluate(
    async ({ src, maxWidth, quality }) => {
      const img = new Image();
      await new Promise((ok, err) => {
        img.onload = () => ok();
        img.onerror = () => err(new Error('decode failed'));
        img.src = src;
      });
      const w = img.naturalWidth || maxWidth;
      const h = img.naturalHeight || Math.round(maxWidth * 0.6);
      const scale = Math.min(1, maxWidth / w);
      const canvas = document.createElement('canvas');
      canvas.width = Math.max(1, Math.round(w * scale));
      canvas.height = Math.max(1, Math.round(h * scale));
      const ctx = canvas.getContext('2d');
      if (!ctx) return null;
      ctx.fillStyle = '#ffffff'; // JPEG has no alpha; demo theme is light
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
      return canvas.toDataURL('image/jpeg', quality);
    },
    { src, maxWidth: MAX_WIDTH, quality: JPEG_QUALITY },
  );
}

const dataUrls = new Map();
for (const url of urls) {
  const img = await fetchImage(url);
  if (!img) continue;
  let dataUrl = null;
  try {
    dataUrl = await recodeToJpeg(img.buf, img.mime);
  } catch {
    dataUrl = null;
  }
  dataUrls.set(url, dataUrl ?? `data:${img.mime};base64,${img.buf.toString('base64')}`);
}
await browser.close();

let inlined = 0;
let kept = 0;
for (const s of sections) {
  for (const e of s.entries) {
    if (!e.imageUrl) continue;
    const m = /^\/api\/seedimg\/[a-z-]+\/([a-z-]+\.svg)$/.exec(e.imageUrl);
    const src = m ? BASE + `/seed/${m[1]}` : e.imageUrl;
    const dataUrl = dataUrls.get(src);
    if (dataUrl) {
      e.imageUrl = dataUrl;
      inlined++;
    } else {
      kept++;
    }
  }
}

const header =
  `/* Generated by scripts/make-demo-snapshot.mjs — do not edit by hand.\n` +
  ` * Offline fallback content for the single-file export build.\n */\n` +
  `import type { PublishedSection } from 'shared/types';\n\n` +
  `export const DEMO_SECTIONS: PublishedSection[] = `;

writeFileSync(
  new URL('../client/src/lib/demoSnapshot.ts', import.meta.url),
  header + JSON.stringify(sections, null, 2) + ';\n',
);
console.log(`demoSnapshot.ts written: ${sections.length} sections, ${inlined} images inlined, ${kept} kept as URL`);
